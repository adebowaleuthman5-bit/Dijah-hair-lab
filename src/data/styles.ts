export const getStyleById = (id: string) => styles.find((s) => s.id === id);
export const getStylesByService = (serviceId: string) =>
  styles.filter((s) => s.serviceId === serviceId && s.bookable);
export const getFeaturedStyles = () => styles.filter((s) => s.isFeatured);
export const getNewArrivals = () => styles.filter((s) => s.isNewArrival);
export const getPopularStyles = () => styles.filter((s) => s.isPopular);

// See src/data/services.ts's replaceServices() for why an in-place mutation
// (not reassignment) is what makes this visible to every importer.
export function replaceStyles(live: Style[]) {
  styles.length = 0;
  styles.push(...live);
}
